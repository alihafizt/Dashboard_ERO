-- 1. Tabel untuk menyimpan ringkasan metrik (per tarikan data)
CREATE TABLE IF NOT EXISTS public.review_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scraped_at TIMESTAMPTZ DEFAULT NOW(),
    store TEXT NOT NULL,
    total_reviews INT NOT NULL DEFAULT 0,
    avg_rating NUMERIC(3,2) NOT NULL DEFAULT 0,
    delta_reviews INT DEFAULT 0,
    delta_rating NUMERIC(4,2) DEFAULT 0
);

-- 2. Tabel untuk menyimpan detail ulasan
CREATE TABLE IF NOT EXISTS public.review_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scraped_at TIMESTAMPTZ DEFAULT NOW(),
    store TEXT NOT NULL,
    author TEXT NOT NULL,
    rating_num INT NOT NULL DEFAULT 5,
    rating_text TEXT,
    time_ago TEXT,
    review_text TEXT,
    is_negative BOOLEAN DEFAULT FALSE,
    review_id TEXT UNIQUE
);

-- 3. Beri akses Read (SELECT) untuk public/anon & Insert
ALTER TABLE public.review_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.review_log ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read review_metrics" ON public.review_metrics FOR SELECT USING (true);
CREATE POLICY "Allow public insert review_metrics" ON public.review_metrics FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read review_log" ON public.review_log FOR SELECT USING (true);
CREATE POLICY "Allow public insert review_log" ON public.review_log FOR INSERT WITH CHECK (true);
